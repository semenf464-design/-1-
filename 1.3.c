#include <stdio.h>

/** Число миллиметров в одном метре (для перевода x в метры). */
#define MM_IN_METER 1000.0

/**
 * @brief Вычисляет потенциальную энергию растянутой пружины.
 *
 * Используется формула E = k * x^2 / 2.
 *
 * @param k Коэффициент жёсткости пружины, Н/м.
 * @param x_m Растяжение пружины, м.
 * @return Потенциальная энергия пружины, Дж.
 */
double spring_energy(double k, double x_m) {
    return k * x_m * x_m / 2.0;
}

/**
 * @brief Точка входа в программу.
 *
 * Считывает растяжение пружины в миллиметрах и коэффициент жёсткости
 * в Н/м, переводит растяжение в метры, вычисляет потенциальную энергию
 * и выводит результат.
 *
 * @return 0 при успешном завершении, 1 при ошибке ввода.
 */
int main() {
    double x_mm = 0.0; /* растяжение пружины, мм */
    double k = 0.0;    /* коэффициент жёсткости, Н/м */

    /* Ввод растяжения; проверяем, что введено число */
    printf("Введите растяжение пружины x, мм: ");
    if (scanf("%lf", &x_mm) != 1) {
        fprintf(stderr, "Ошибка: x должно быть числом.\n");
        return 1;
    }

    /* Ввод жёсткости; проверяем, что введено число */
    printf("Введите коэффициент жёсткости k, Н/м: ");
    if (scanf("%lf", &k) != 1) {
        fprintf(stderr, "Ошибка: k должно быть числом.\n");
        return 1;
    }

    /* Проверка физического смысла: растяжение не отрицательно, жёсткость положительна */
    if (x_mm < 0.0) {
        fprintf(stderr, "Ошибка: растяжение не может быть отрицательным.\n");
        return 1;
    }
    if (k <= 0.0) {
        fprintf(stderr, "Ошибка: жёсткость должна быть положительной.\n");
        return 1;
    }

    /* Перевод миллиметров в метры */
    double x_m = x_mm / MM_IN_METER;

    /* Расчёт энергии по формуле E = k * x^2 / 2 */
    double energy = spring_energy(k, x_m);

    /* Вывод результата */
    printf("Потенциальная энергия пружины: %.6f Дж\n", energy);

    return 0;
}
